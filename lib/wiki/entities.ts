/**
 * lib/wiki/entities.ts — the entity layer: a typed graph over repo truth.
 *
 * WHY this file exists:
 *   lib/wiki/graph.ts derives ONE graph: documents joined by markdown
 *   links. That graph answers "what should I read next", but it cannot
 *   answer "which syndicates call web_search", "what breaks without
 *   XAI_API_KEY", or "which decision constrains the export pipeline" —
 *   because the things those questions name (agents, tools, models,
 *   tables, env vars, decisions) are not documents. They are ENTITIES,
 *   and the relations between them are typed, not hyperlinks.
 *
 *   This module is that second layer, and it keeps the same discipline as
 *   the first: nodes and edges are DERIVED from repo truth wherever a
 *   parser can see them, and merely ASSERTED where only judgment can.
 *   The two tiers are labelled, never mixed:
 *
 *     extracted — a parser read it out of a YAML, a contract, DDL, an
 *                 import statement, a link. Rebuildable, disposable,
 *                 always regenerated by `wiki:build --graph`.
 *     inferred  — a human or an agent read prose and asserted it, with
 *                 evidence and an actor id. Never machine-overwritten;
 *                 lives in .graph/relations.json beside the snapshot.
 *
 *   Everything here is bundle-agnostic. WHAT to extract from (this repo's
 *   agent YAMLs, its SQL, its package.json) is the caller's business —
 *   scripts/wiki/build.ts does that privately. This module owns the
 *   vocabulary, the graph mechanics, the two stores, and the lint rules,
 *   including the same private-closure invariant the document lint
 *   enforces (wiki/decisions/0003): a public node may never point at a
 *   private one, so any public slice of this graph is closed by
 *   construction.
 */

